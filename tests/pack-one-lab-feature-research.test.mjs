import test from 'node:test';
import assert from 'node:assert/strict';
import {createFeatureResearch,featureResearchPackets,validateFeaturePacket} from '../research/pack-one-lab/feature-research.mjs';
import {summarizeStoredSet} from '../research/pack-one-lab/stored-corpus.mjs';
import {assembleArticle,writerRequest,reviewerRequest} from '../worker/lab-writer.mjs';
import {labPost} from '../lab-patreon-contract.mjs';
const meta={set_id:'fra',set_name:'Fixture Set',corpus_version:'fixture',source_snapshot_id:'a'.repeat(64),draft_sha256:'b'.repeat(64),game_sha256:'c'.repeat(64)};
const card=(id,mana)=>({id,name:id,mana_cost:mana,rarity:'common',type_line:'Creature',multi_face:false});
const target=card('Fixture Mage','{1}{U}'),blue=card('Blue Creature','{2}{U}'),red=card('Red Creature','{1}{R}'),black=card('Black Creature','{2}{B}');
const cards=[target,blue,red,black];
function fixture(){
 const rows=[];
 // The lead association is generated by early color selection. The
 // within-color comparison has independently supported groups and shrinks it.
 const groups=[
  {n:110,early:['Red Creature','Black Creature','Red Creature'],taken:10},
  {n:45,early:['Blue Creature','Red Creature','Red Creature'],taken:22},
  {n:35,early:['Fixture Mage','Red Creature','Red Creature'],taken:25},
  {n:60,early:['Blue Creature','Blue Creature','Red Creature'],taken:43},
  {n:40,early:['Fixture Mage','Blue Creature','Red Creature'],taken:32}
 ];
 let id=0;
 for(const g of groups)for(let i=0;i<g.n;i++){
  const hash=(++id).toString(16).padStart(32,'0');
  for(let p=1;p<=8;p++){
   // Only P1P4 offers the named card after the early choices; no later
   // offers contaminate the independent group counts.
   const offered=p<=4?cards:[blue,red,black];
   const chosen=p<=3?g.early[p-1]:p===4&&i<g.taken?target.id:red.id;
   rows.push({source_draft_hash:hash,pick_number:p,historical_pick_id:chosen,candidates:offered});
  }
 }
 const raw=summarizeStoredSet(meta,rows);
 raw.rules_context={set_id:'fra',sha256:'5dee48cee16adf09b5c1003c4ef9af88a4951e4c24e7f7ba47283e444b80dfd7',cards:{'Fixture Mage':{oracle_text:'Whenever you draw your second card each turn, put a +1/+1 counter on Fixture Mage.',type_line:'Creature'}}};
 return {schema_version:1,kind:'stored-corpus',sets:[raw]};
}
test('repeat story tests the aggregate association inside two supported color groups',()=>{
 const report=fixture(),p=featureResearchPackets(report).find(x=>x.feature.family==='repeat-context'&&x.research_context.cards[0].name===target.name);
 assert.ok(p);
 const values=Object.fromEntries(p.metrics.map(m=>[m.id,[m.numerator,m.denominator,m.distinct_drafts]]));
 assert.deepEqual(values.fresh,[75,215,215]);
 assert.deepEqual(values.prior,[57,75,75]);
 assert.deepEqual(values['fresh-one'],[22,45,45]);
 assert.deepEqual(values['prior-one'],[25,35,35]);
 assert.deepEqual(values['fresh-many'],[43,60,60]);
 assert.deepEqual(values['prior-many'],[32,40,40]);
 assert.equal(validateFeaturePacket(p).version,'feature-v2');
 assert.ok(!JSON.stringify(report).includes('00000000000000000000000000000001'));
 const absent=structuredClone(report);delete absent.sets[0].rules_context;
 assert.equal(featureResearchPackets(absent).length,0);
 const weak=structuredClone(p);weak.metrics.find(m=>m.id==='prior-one').distinct_drafts=9;
 assert.throws(()=>validateFeaturePacket(weak),/lab-feature-evidence/);
 const missing=structuredClone(p);missing.feature.follow_up_ids=[];
 assert.throws(()=>validateFeaturePacket(missing),/lab-feature-evidence/);
});
test('feature gate rejects short or missing-hook articles and supplies two actual charts',()=>{
 const p=featureResearchPackets(fixture()).find(x=>x.feature.family==='repeat-context'&&x.research_context.cards[0].name===target.name);
 assert.ok(p);
 const req=writerRequest(p);
 assert.deepEqual(req.input.editorial.prose_words,[300,500]);
 assert.equal(req.input.editorial.max_sections,3);
 assert.equal(req.input.evidence.feature.follow_up_ids.length,4);
 const short={title:'Fixture Mage',lead:'Fixture Mage is a blue creature.',sections:[],closing:''};
 assert.throws(()=>assembleArticle(p,short),/article-length/);
 const copy={title:'Another Fixture Mage',lead:'Fixture Mage rewards a second draw. The first copy might look like a cheap threat and the next one can grow from the same extra draw. Suppose the pack has another Mage and a creature that helps you draw cards. The two choices fill different jobs. Before treating the repeat pick as evidence that you need a second Mage, it helps to see how the first pick affects the cards that can fit the deck.',
 sections:[
 {heading:'The early picks',text:'The Mage was picked [stat:fresh:pct] without an earlier copy and [stat:prior:pct] when a copy had already been picked. Those offers come from trophy drafts, not every draft played in the format. A player who already has a Mage also has a reason to draft blue. The earlier color picks therefore deserve a closer look. When there was no prior pick in its color, the rate was [stat:fresh-zero:pct]. Some of those pools may not have had a place for the Mage at all.'},
 {heading:'Compare similar pools',text:'With one earlier pick in its color, the rate was [stat:fresh-one:pct] without a Mage and [stat:prior-one:pct] with a Mage. With at least two earlier picks in its color, the rates were [stat:fresh-many:pct] and [stat:prior-many:pct]. Counting blue picks does not tell you what other cards were in the pack or whether the drafter had a good reason to play that color. It does help separate the apparent demand for an extra copy from the basic question of whether a blue card can make the deck.'},
 {heading:'',text:'A Mage gets bigger when its controller draws a second card in a turn. A pair of Mages can benefit from the same draw, but neither makes that draw happen. The imaginary pack at the start of the article is therefore a real deck building dilemma: do you need another payoff or another way to trigger the ones you have? That answer depends on the spells already in the pool and the alternatives you can actually take.'}],
 closing:'These are pick rates in successful drafts, not game results for decks with a given number of copies. The next useful check would be how the decks played.'};
 const article=assembleArticle(p,copy);
 assert.equal(article.style_version,'feature-v2');
 assert.equal(article.blocks.filter(b=>b.type==='chart').length,1);
 assert.equal(article.blocks.filter(b=>b.type==='outcome-chart').length,1);
 assert.match(article.artwork.outcome_chart_alt,/One color pick, no copy/);
 assert.ok(labPost(article).body.length<=3999);
 assert.match(reviewerRequest(p,article).system,/Reject dry chart narration/);
 const noHook=structuredClone(copy);
 noHook.sections[1].text=noHook.sections[1].text.replace('[stat:prior-many:pct]','an unmeasured alternative');
 assert.throws(()=>assembleArticle(p,noHook),/missing-feature-investigation/);
});

-- Lab editorial queue, additive; no publication action or schedule here.
-- Apply through reviewed schema release, never from the article worker.
CREATE TABLE IF NOT EXISTS pack1_lab_issues (
  week_key date PRIMARY KEY,
  state text NOT NULL CHECK(state IN ('researching','review','revision_requested','alternative_requested','approved','skipped','no_finding')),
  revision integer NOT NULL DEFAULT 0 CHECK(revision>=0),
  candidate_id text,
  attempted_ids text[] NOT NULL DEFAULT ARRAY[]::text[],
  article jsonb,
  candidate_evidence jsonb,
  article_hash text CHECK(article_hash IS NULL OR article_hash ~ '^[0-9a-f]{64}$'),
  approved_hash text CHECK(approved_hash IS NULL OR approved_hash ~ '^[0-9a-f]{64}$'),
  approved_at timestamptz,
  approved_by uuid,
  publish_at timestamptz,
  feedback text CHECK(feedback IS NULL OR length(feedback)<=1500),
  notification_sent_at timestamptz,
  notification_claimed_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((article IS NULL) = (article_hash IS NULL)),
  CHECK (state <> 'review' OR (article IS NOT NULL AND revision>0)),
  CHECK (state <> 'approved' OR (article IS NOT NULL AND approved_hash IS NOT NULL AND approved_hash=article_hash AND approved_at IS NOT NULL AND approved_by IS NOT NULL AND publish_at IS NOT NULL)),
  CHECK (state = 'approved' OR (approved_hash IS NULL AND approved_at IS NULL AND approved_by IS NULL AND publish_at IS NULL))
);
-- statement
CREATE TABLE IF NOT EXISTS pack1_lab_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  week_key date NOT NULL REFERENCES pack1_lab_issues(week_key),
  revision integer NOT NULL,
  action text NOT NULL CHECK(action IN ('review_ready','approve','approve_now','revise','alternative','skip')),
  owner_id uuid,
  article_hash text,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- statement
CREATE TABLE IF NOT EXISTS pack1_lab_research (
  source_key text PRIMARY KEY,
  state text NOT NULL CHECK(state IN ('preparing','ready','failed')),
  attempted_at timestamptz NOT NULL DEFAULT now(),
  report jsonb,
  report_hash text CHECK(report_hash IS NULL OR report_hash ~ '^[0-9a-f]{64}$'),
  CHECK ((state='ready') = (report IS NOT NULL AND report_hash IS NOT NULL))
);
-- statement
REVOKE ALL ON pack1_lab_issues, pack1_lab_events, pack1_lab_research FROM PUBLIC;
-- statement
-- Only retained, approved public-source decisions are projected. This is NOT
-- the serving inventory: model-support/interest/difficulty filters would bias
-- the observed choice rates. Exclusions/removals remain respected.
CREATE OR REPLACE VIEW public.pack1_lab_corpus_sources WITH (security_barrier=true) AS
SELECT e.set_id,e.set_name,e.release_date,s.corpus_version,s.source_snapshot_id,s.draft_sha256,s.game_sha256
FROM public.draft_run_environment_policy e
JOIN public.corpus_source_snapshots s ON s.source_snapshot_id=e.active_snapshot_id
  AND s.set_id=e.set_id AND s.event_type='PremierDraft' AND s.lifecycle_status='Approved'
WHERE e.status='Live' AND e.regular_run AND e.source_event_type='PremierDraft'
  AND s.draft_sha256 ~ '^[0-9a-f]{64}$' AND s.game_sha256 ~ '^[0-9a-f]{64}$';
-- statement
CREATE OR REPLACE VIEW public.pack1_lab_corpus_picks WITH (security_barrier=true) AS
SELECT e.set_id,e.set_name,e.release_date,p.corpus_version,p.source_snapshot_id,
       e.draft_sha256,e.game_sha256,p.source_draft_hash,p.pick_number,
       p.payload->>'historical_pick_id' AS historical_pick_id,
       (SELECT jsonb_agg(jsonb_build_object(
         'id',c->>'id','name',c->>'name','rarity',c->>'rarity',
         'mana_cost',c->>'mana_cost','type_line',c->>'type_line',
         'multi_face',(c ? 'display_faces' OR c ? 'card_faces' OR coalesce(c->>'type_line','') LIKE '%//%' OR coalesce(c->>'mana_cost','') LIKE '%//%')
       ) ORDER BY ordinality)
       FROM jsonb_array_elements(CASE WHEN jsonb_typeof(p.payload->'candidates')='array'
         THEN p.payload->'candidates' ELSE '[]'::jsonb END) WITH ORDINALITY AS a(c,ordinality)) AS candidates
FROM public.pack1_lab_corpus_sources e
JOIN public.draft_run_verified_puzzles p ON p.set_id=e.set_id
  AND p.source_snapshot_id=e.source_snapshot_id AND p.corpus_version=e.corpus_version
WHERE p.pack_number=1 AND p.pick_number BETWEEN 1 AND 8
  AND p.payload->>'source_evidence'='official_archive_trajectory'
  AND p.payload->>'skill_evidence'='win_rate_bucket'
  AND p.payload->>'event_match_wins'='7'
  AND (CASE WHEN jsonb_typeof(p.payload->'player_games_lower_bound')='number'
        THEN (p.payload->>'player_games_lower_bound')::numeric ELSE 0 END)>=100
  AND (CASE WHEN jsonb_typeof(p.payload->'player_win_rate_bucket')='number'
        THEN (p.payload->>'player_win_rate_bucket')::numeric ELSE 0 END) BETWEEN .60 AND 1
  AND NOT EXISTS (SELECT 1 FROM public.corpus_source_exclusions x WHERE x.set_id=p.set_id
    AND x.corpus_version=p.corpus_version AND x.source_draft_hash=p.source_draft_hash)
  AND NOT EXISTS (SELECT 1 FROM public.draft_run_pick_removal_members m
    JOIN public.draft_run_pick_removals x USING(decision_key) WHERE m.puzzle_id=p.puzzle_id AND x.removed);
-- statement
REVOKE ALL ON public.pack1_lab_corpus_picks, public.pack1_lab_corpus_sources FROM PUBLIC;


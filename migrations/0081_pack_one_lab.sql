-- Lab editorial queue, additive; no publication action or schedule here.
-- Apply through reviewed schema release, never from the article worker.
CREATE TABLE IF NOT EXISTS pack1_lab_issues (
  week_key date PRIMARY KEY,
  state text NOT NULL CHECK(state IN ('researching','review','revision_requested','alternative_requested','approved','skipped','no_finding')),
  revision integer NOT NULL DEFAULT 0 CHECK(revision>=0),
  candidate_id text,
  article jsonb,
  article_hash text CHECK(article_hash IS NULL OR article_hash ~ '^[0-9a-f]{64}$'),
  approved_hash text CHECK(approved_hash IS NULL OR approved_hash ~ '^[0-9a-f]{64}$'),
  approved_at timestamptz,
  approved_by uuid,
  publish_at timestamptz,
  feedback text CHECK(feedback IS NULL OR length(feedback)<=1500),
  notification_sent_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((article IS NULL) = (article_hash IS NULL)),
  CHECK (state <> 'review' OR (article IS NOT NULL AND revision>0)),
  CHECK (state <> 'approved' OR (article IS NOT NULL AND approved_hash IS NOT NULL AND approved_hash=article_hash AND approved_at IS NOT NULL AND approved_by IS NOT NULL AND publish_at IS NOT NULL)),
  CHECK (state = 'approved' OR (approved_hash IS NULL AND approved_at IS NULL AND approved_by IS NULL AND publish_at IS NULL))
);
-- statement
CREATE TABLE IF NOT EXISTS pack1_lab_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  week_key date NOT NULL REFERENCES pack1_lab_issues(week_key),
  revision integer NOT NULL,
  action text NOT NULL CHECK(action IN ('review_ready','approve','approve_now','revise','alternative','skip')),
  owner_id uuid,
  article_hash text,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- statement
REVOKE ALL ON pack1_lab_issues, pack1_lab_events FROM PUBLIC;

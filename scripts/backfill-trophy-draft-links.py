"""Resolve stored trophy sources to their original public 17Lands draft URLs.

Only the existing catalogs' source hashes are matched. Reading game archives
does not alter decks, quantities, source membership, or puzzle publication.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
import csv
import gzip
import hashlib
import json
from pathlib import Path
import re
import subprocess
import urllib.request

from importlib.util import module_from_spec, spec_from_file_location

ROOT = Path(__file__).resolve().parents[1]
spec = spec_from_file_location('extract_trophy_decks', ROOT / 'scripts/extract-trophy-decks.py')
extractor = module_from_spec(spec)
spec.loader.exec_module(extractor)


def draft_url(draft_id):
    if not re.fullmatch('[a-f0-9]{32}', draft_id or ''):
        raise ValueError('Invalid public draft identity')
    return 'https://www.17lands.com/draft/' + draft_id


def resolve_archive(path, set_id, event_type, wanted, expansion=None):
    """Match exact source hashes; never infer a draft from card similarity."""
    found, seen = {}, set()
    with gzip.open(path, 'rt', encoding='utf-8-sig', newline='') as source:
        header = next(csv.reader([source.readline()]))
        index = header.index('draft_id')
        for line in source:
            # The archive's fixed metadata prefix precedes all card columns.
            identity = line.split(',', index + 1)[index].strip('"')
            if identity in seen:
                continue
            seen.add(identity)
            url = draft_url(identity)
            for alias in extractor.source_aliases(set_id, event_type, identity, expansion):
                if alias in wanted:
                    if alias in found and found[alias] != url:
                        raise ValueError('Conflicting public draft identities')
                    found[alias] = url
    return found


def add_links(catalog, links):
    by_deck = {}
    for source, index in catalog['sources'].items():
        if source not in links:
            raise ValueError(catalog['set_id'] + ': missing public draft identity')
        url = links[source]
        draft_url(url.removeprefix('https://www.17lands.com/draft/'))
        if index in by_deck and by_deck[index] != url:
            raise ValueError('Aliases disagree about the public draft')
        by_deck[index] = url
    if len(by_deck) != len(catalog['decks']):
        raise ValueError('Unreferenced trophy deck')
    for index, url in by_deck.items():
        catalog['decks'][index]['draft_url'] = url
    return catalog


def read_catalog(path):
    script = "import{pathToFileURL}from'node:url';const{encoded}=await import(pathToFileURL(process.argv[1]));const{decodeTrophyDeckCatalog}=await import(pathToFileURL(process.argv[2]));process.stdout.write(JSON.stringify(decodeTrophyDeckCatalog(encoded)));"
    return json.loads(subprocess.check_output(['node', '--input-type=module', '-e', script, str(path),
                                              str(ROOT / 'worker/trophy-decks.mjs')]))


def write_catalog(path, catalog):
    raw = json.dumps(extractor.compact_catalog(catalog), separators=(',', ':'), sort_keys=True).encode()
    script = "import{brotliCompressSync,constants}from'node:zlib';const chunks=[];for await(const chunk of process.stdin)chunks.push(chunk);process.stdout.write(brotliCompressSync(Buffer.concat(chunks),{params:{[constants.BROTLI_PARAM_QUALITY]:11}}).toString('base64'));"
    packed = subprocess.run(['node', '--input-type=module', '-e', script], input=raw,
                            stdout=subprocess.PIPE, check=True).stdout.decode()
    path.write_text('// Generated by scripts/build-trophy-deck-catalog.py. See README.md for provenance.\n'
                    + 'export const sha256=' + json.dumps(hashlib.sha256(raw).hexdigest()) + ';\n'
                    + 'export const encoded=' + json.dumps(packed) + ';\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache', required=True, type=Path)
    parser.add_argument('--workers', type=int, default=4)
    parser.add_argument('--catalog-dir', type=Path, default=ROOT / 'corpus/trophy-decks')
    args = parser.parse_args()
    coverage = json.loads((args.catalog_dir / 'coverage.json').read_text())
    catalogs = {row['set_id']: read_catalog(args.catalog_dir / (row['set_id'] + '.mjs'))
                for row in coverage['sets']}
    args.cache.mkdir(parents=True, exist_ok=True)

    def resolve(archive):
        sid, event = archive['set_id'], archive['event_type']
        url = archive['archive_url'].strip()
        if not re.fullmatch(r'https://17lands-public\.s3\.amazonaws\.com/analysis_data/game_data/game_data_public\.[A-Za-z0-9_-]+\.(PremierDraft|TradDraft)\.csv\.gz', url):
            raise ValueError('Unexpected archive URL')
        path = args.cache / (sid + '-' + event + '.csv.gz')
        if not path.exists():
            temporary = path.with_suffix('.partial')
            with urllib.request.urlopen(url, timeout=90) as source, temporary.open('wb') as target:
                while block := source.read(1024 * 1024):
                    target.write(block)
            temporary.replace(path)
        digest = hashlib.sha256()
        with path.open('rb') as source:
            while block := source.read(1024 * 1024):
                digest.update(block)
        expansion = url.split('game_data_public.', 1)[1].split('.', 1)[0]
        wanted = set(catalogs[sid]['sources'])
        links = resolve_archive(path, sid, event, wanted, expansion)
        return sid, event, links, {'set_id': sid, 'event_type': event, 'archive_url': url,
                                 'archive_sha256': digest.hexdigest(), 'sources': len(links)}

    links, reports = {}, []
    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        futures = [pool.submit(resolve, archive) for archive in coverage['archives']]
        for future in as_completed(futures):
            sid, event, found, report = future.result()
            current = links.setdefault(sid, {})
            if any(key in current and current[key] != url for key, url in found.items()):
                raise ValueError('Archives disagree about the public draft')
            current.update(found)
            reports.append(report)
            print(json.dumps({'set': sid, 'event': event, 'resolved': len(found)}), flush=True)
    # Validate completeness before changing any catalog.
    for sid, catalog in catalogs.items():
        add_links(catalog, links.get(sid, {}))
    for sid, catalog in catalogs.items():
        write_catalog(args.catalog_dir / (sid + '.mjs'), catalog)
    report = {'schema_version': 1, 'sources': sum(len(c['sources']) for c in catalogs.values()),
              'archives': sorted(reports, key=lambda row: (row['set_id'], row['event_type']))}
    (args.catalog_dir / 'draft-links.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps({'sets': len(catalogs), 'sources': report['sources']}), flush=True)


if __name__ == '__main__':
    main()

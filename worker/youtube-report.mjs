// Read-only YouTube channel report for Admin Insights: each recent Short's
// format, views, engaged views and retention at the debate format's scene
// changes. Uses a separate read-only credential; never the upload token.
const TOKEN_URL='https://oauth2.googleapis.com/token';
const DATA_API='https://www.googleapis.com/youtube/v3/';
const ANALYTICS_API='https://youtubeanalytics.googleapis.com/v2/reports';
const LOOKBACK_DAYS=60;
const CACHE_MS=10*60*1000;
// Debate Short scene changes: cards and hook end at 3 s, decision time at
// 9 s, the reveal at 15 s, of 20 s.
export const RETENTION_POINTS=Object.freeze([{label:'3s',ratio:.15},{label:'9s',ratio:.45},{label:'15s',ratio:.75}]);
const METRICS=['views','engagedViews','averageViewDuration','averageViewPercentage','likes','shares','subscribersGained'];
const BASIC_METRICS=['views','averageViewDuration','averageViewPercentage','likes'];
let cache=null;

export function youtubeReportConfigured(env=process.env) {
  return Boolean(env.PACKONE_YOUTUBE_ANALYTICS_CLIENT_ID&&env.PACKONE_YOUTUBE_ANALYTICS_CLIENT_SECRET&&
    env.PACKONE_YOUTUBE_ANALYTICS_REFRESH_TOKEN);
}
// Titles are generated by the publishers, so they identify each format.
export function shortFormat(title='') {
  if(title.startsWith('Which Would You Draft?'))return 'debate';
  if(/-Way MTG Draft Split/.test(title))return 'featured_v1';
  if(title.startsWith('Today\'s MTG Draft Pick | Pack One'))return 'daily_generic';
  return 'other';
}
const day=d=>d.toISOString().slice(0,10);
async function googleJson(fetcher,url,{token,label,body}) {
  const response=await fetcher(url,{
    method:body?'POST':'GET',
    headers:body?{'content-type':'application/x-www-form-urlencoded'}:{authorization:'Bearer '+token},
    ...(body?{body}:{}),
    signal:AbortSignal.timeout(15_000),
  });
  // Never echo provider bodies: they can include account details.
  if(!response.ok)throw Object.assign(Error(label+' returned HTTP '+response.status+'.'),{status:response.status});
  return response.json();
}
async function accessToken(fetcher,env) {
  const json=await googleJson(fetcher,TOKEN_URL,{label:'YouTube Analytics sign-in',body:new URLSearchParams({
    client_id:env.PACKONE_YOUTUBE_ANALYTICS_CLIENT_ID,client_secret:env.PACKONE_YOUTUBE_ANALYTICS_CLIENT_SECRET,
    refresh_token:env.PACKONE_YOUTUBE_ANALYTICS_REFRESH_TOKEN,grant_type:'refresh_token'})});
  if(typeof json.access_token!=='string')throw Error('YouTube Analytics sign-in returned no access token.');
  return json.access_token;
}
async function recentUploads(fetcher,token,since) {
  const channel=await googleJson(fetcher,DATA_API+'channels?part=contentDetails&mine=true',{token,label:'YouTube channel lookup'});
  const playlist=channel.items?.[0]?.contentDetails?.relatedPlaylists?.uploads;
  if(!playlist)throw Error('YouTube channel has no uploads playlist.');
  const url=new URL(DATA_API+'playlistItems');
  url.searchParams.set('part','snippet,contentDetails');url.searchParams.set('playlistId',playlist);url.searchParams.set('maxResults','50');
  const list=await googleJson(fetcher,url.toString(),{token,label:'YouTube uploads lookup'});
  return (list.items||[]).map(item=>({id:item.contentDetails?.videoId,title:String(item.snippet?.title||''),
    published_at:item.contentDetails?.videoPublishedAt||item.snippet?.publishedAt||null}))
    .filter(v=>/^[A-Za-z0-9_-]{11}$/.test(v.id||'')&&v.published_at&&v.published_at.slice(0,10)>=since);
}
function rowsByVideo(json) {
  const names=(json.columnHeaders||[]).map(h=>h.name);
  return new Map((json.rows||[]).map(row=>[row[0],Object.fromEntries(names.slice(1).map((n,i)=>[n,row[i+1]]))]));
}
async function videoMetrics(fetcher,token,since,until) {
  const query=metrics=>{
    const url=new URL(ANALYTICS_API);
    for(const [k,v] of Object.entries({ids:'channel==MINE',startDate:since,endDate:until,metrics:metrics.join(','),
      dimensions:'video',sort:'-views',maxResults:'200'}))url.searchParams.set(k,v);
    return googleJson(fetcher,url.toString(),{token,label:'YouTube Analytics video report'});
  };
  // If the API rejects the fuller metric set, keep the basics rather than nothing.
  try {return {metrics:rowsByVideo(await query(METRICS)),engaged_views_available:true};}
  catch(error) {
    if(error.status!==400)throw error;
    return {metrics:rowsByVideo(await query(BASIC_METRICS)),engaged_views_available:false};
  }
}
async function retention(fetcher,token,id,since,until) {
  const url=new URL(ANALYTICS_API);
  for(const [k,v] of Object.entries({ids:'channel==MINE',startDate:since,endDate:until,metrics:'audienceWatchRatio',
    dimensions:'elapsedVideoTimeRatio',filters:'video=='+id}))url.searchParams.set(k,v);
  const rows=(await googleJson(fetcher,url.toString(),{token,label:'YouTube retention report'})).rows||[];
  if(!rows.length)return null;
  // The closest reported point at or before each scene change.
  return Object.fromEntries(RETENTION_POINTS.map(({label,ratio})=>{
    const point=rows.filter(r=>Number(r[0])<=ratio+1e-9).at(-1);
    return [label,point?Math.round(1000*Number(point[1]))/10:null];
  }));
}

export async function youtubeReport({env=process.env,fetcher=fetch,now=new Date(),useCache=true}={}) {
  if(!youtubeReportConfigured(env))return {configured:false};
  if(useCache&&cache&&now.getTime()-cache.at<CACHE_MS)return cache.report;
  const until=day(now),since=day(new Date(now.getTime()-LOOKBACK_DAYS*86400_000));
  const token=await accessToken(fetcher,env);
  const uploads=await recentUploads(fetcher,token,since);
  const {metrics,engaged_views_available}=await videoMetrics(fetcher,token,since,until);
  const videos=[];
  for(const video of uploads) {
    const format=shortFormat(video.title),m=metrics.get(video.id)||{};
    videos.push({...video,format,views:m.views??0,engaged_views:m.engagedViews??null,
      average_view_seconds:m.averageViewDuration??null,average_view_pct:m.averageViewPercentage??null,
      likes:m.likes??0,shares:m.shares??null,subscribers_gained:m.subscribersGained??null,
      retention:format==='debate'?await retention(fetcher,token,video.id,since,until).catch(()=>null):null});
  }
  const report={configured:true,generated_at:now.toISOString(),since,until,engaged_views_available,
    retention_points:RETENTION_POINTS.map(p=>p.label),videos};
  cache={at:now.getTime(),report};
  return report;
}
export function clearYoutubeReportCache(){cache=null;}

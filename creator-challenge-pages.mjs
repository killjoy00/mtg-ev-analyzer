import {buildCampaignTrackingUrl,normalizeAcquisitionValue,normalizeCampaignSlug} from './campaign-links.mjs';

export const GENERATED_CREATOR_MARKER='<!-- Generated by scripts/prepare-creator-challenge-publish.mjs. Do not edit by hand. -->';
const UUID=/^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/;
const html=value=>String(value??'').replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');
const plain=(value,max)=>{
  const text=String(value??'').trim();
  if(!text||text.length>max||/[\u0000-\u001f\u007f]/.test(text))throw Error('Invalid creator challenge text.');
  return text;
};
const envLabel=value=>value==='powered-cube'?'Powered Cube':value==='latest'?'Latest Set':'Draft Run';

function dayLabel(value) {
  if(!/^\d{4}-\d{2}-\d{2}$/.test(String(value||'')))return null;
  const date=new Date(String(value)+'T12:00:00Z');
  return new Intl.DateTimeFormat('en-US',{month:'long',day:'numeric',year:'numeric',timeZone:'UTC'}).format(date);
}

export function validateCreatorPageEntries(input) {
  if(!Array.isArray(input))throw Error('creator-challenges.json must contain an array.');
  const slugs=new Set(),ids=new Set();
  return input.map((raw,index)=>{
    const label=`creator-challenges.json entry ${index+1}`;
    if(!raw||typeof raw!=='object'||Array.isArray(raw))throw Error(`${label} must be an object.`);
    const status=String(raw.status||'');
    if(!['published','retired'].includes(status))throw Error(`${label} has an invalid status.`);
    const id=String(raw.id||'').toLowerCase(),slug=normalizeCampaignSlug(raw.slug);
    if(!UUID.test(id)||!slug||slug!==raw.slug)throw Error(`${label} has an invalid immutable identity.`);
    if(slugs.has(slug)||ids.has(id))throw Error(`${label} duplicates a creator challenge identity.`);
    slugs.add(slug);ids.add(id);
    if(status==='retired') {
      const allowed=new Set(['id','slug','status']);
      if(Object.keys(raw).some(key=>!allowed.has(key)))throw Error(`${label} retired entries must not retain creator metadata.`);
      return {id,slug,status};
    }
    const allowed=new Set(['id','slug','status','creator_name','headline','score','environment','source_type','source_day','source','campaign','medium']);
    const unknown=Object.keys(raw).filter(key=>!allowed.has(key));
    if(unknown.length)throw Error(`${label} contains unsupported fields: ${unknown.join(', ')}.`);
    const creatorName=plain(raw.creator_name,80),headline=plain(raw.headline,160);
    const score=Number(raw.score);
    if(!Number.isInteger(score)||score<0||score>100)throw Error(`${label} has an invalid score.`);
    const environment=String(raw.environment||'');
    if(!['mixed','powered-cube','latest'].includes(environment))throw Error(`${label} has an invalid environment.`);
    const sourceType=String(raw.source_type||'');
    if(!['practice','daily'].includes(sourceType))throw Error(`${label} has an invalid source type.`);
    const sourceDay=raw.source_day==null?null:String(raw.source_day);
    if((sourceType==='daily')!==Boolean(sourceDay&&/^\d{4}-\d{2}-\d{2}$/.test(sourceDay)))throw Error(`${label} has an invalid source date.`);
    const source=normalizeAcquisitionValue(raw.source),campaign=normalizeAcquisitionValue(raw.campaign);
    const medium=raw.medium==null||raw.medium===''?null:normalizeAcquisitionValue(raw.medium);
    if(!source||!campaign||(raw.medium&&!medium))throw Error(`${label} has invalid acquisition values.`);
    return {id,slug,status,creator_name:creatorName,headline,score,environment,source_type:sourceType,source_day:sourceDay,source,campaign,...(medium?{medium}: {})};
  });
}

export function creatorChallengeDescription(entry) {
  const valid=validateCreatorPageEntries([entry])[0];
  if(valid.status!=='published')return 'This Pack One creator challenge is no longer available.';
  const environment=envLabel(valid.environment);
  if(valid.source_type==='daily')return `${valid.creator_name} scored ${valid.score}/100 on the ${dayLabel(valid.source_day)} ${environment} Daily. Play the same eight decisions.`;
  return `${valid.creator_name} scored ${valid.score}/100 on a Pack One ${environment} Practice run. Play the same eight decisions.`;
}

export function creatorChallengeTrackedUrl(entry) {
  const valid=validateCreatorPageEntries([entry])[0];
  if(valid.status!=='published')throw Error('Retired creator challenges do not have a tracked play URL.');
  return buildCampaignTrackingUrl({
    destination:`/?game=draft-run&creator=${valid.id}`,
    source:valid.source,
    campaign:valid.campaign,
    ...(valid.medium?{medium:valid.medium}:{}),
  },{allowCreator:true});
}

export function renderCreatorChallengePage(entry) {
  const valid=validateCreatorPageEntries([entry])[0];
  const canonical=`https://packone.pro/creator/${valid.slug}/`;
  if(valid.status==='retired')return `${GENERATED_CREATOR_MARKER}
<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex,nofollow"><link rel="canonical" href="${canonical}"><title>Creator challenge unavailable · Pack One</title></head>
<body data-creator-challenge-id="${valid.id}" data-creator-challenge-status="retired"><main><h1>This creator challenge is no longer available.</h1><p><a href="https://packone.pro/">Back to Pack One</a></p></main></body></html>
`;
  const description=creatorChallengeDescription(valid),tracked=creatorChallengeTrackedUrl(valid);
  const image=`${canonical}creator-card.png`;
  return `${GENERATED_CREATOR_MARKER}
<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <meta name="description" content="${html(description)}" />
  <meta name="robots" content="noindex,nofollow" />
  <meta property="og:type" content="website" />
  <meta property="og:title" content="${html(valid.headline)}" />
  <meta property="og:description" content="${html(description)}" />
  <meta property="og:url" content="${canonical}" />
  <meta property="og:image" content="${image}" />
  <meta property="og:image:width" content="1200" />
  <meta property="og:image:height" content="630" />
  <meta property="og:image:alt" content="${html(valid.headline)}" />
  <meta name="twitter:card" content="summary_large_image" />
  <meta name="twitter:title" content="${html(valid.headline)}" />
  <meta name="twitter:description" content="${html(description)}" />
  <meta name="twitter:image" content="${image}" />
  <meta name="twitter:image:alt" content="${html(valid.headline)}" />
  <link rel="canonical" href="${canonical}" />
  <title>${html(valid.headline)} · Pack One</title>
  <script>location.replace(${JSON.stringify(tracked)});</script>
</head>
<body data-creator-challenge-id="${valid.id}" data-creator-challenge-status="published">
  <p>Opening this Pack One creator challenge. <a href="${html(tracked)}">Continue</a>.</p>
</body>
</html>
`;
}
